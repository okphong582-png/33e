const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const bytes=fs.readFileSync(path.join(root,'firebase/assets/license-lock.jpg'));
if(bytes.length>1024*1024||bytes[0]!==0xff||bytes[1]!==0xd8)throw Error('Expected a JPEG under 1 MiB');
const base64=bytes.toString('base64').match(/.{1,100}/g).map(s=>'    @"'+s+'"').join('\n');
fs.writeFileSync(path.join(root,'sources/LicenseLockImage.inc'),'// Generated by tools/embed_license_lock_image.cjs; do not edit.\nstatic NSString * const MizzeLicenseLockImage =\n'+base64+';\n');
